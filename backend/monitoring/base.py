from abc import ABC, abstractmethod
from typing import Optional, List, Dict, Any
import numpy as np
from pydantic import BaseModel, Field, ConfigDict


class DetectionBox(BaseModel):
    """Bounding box for detected object."""
    x1: int
    y1: int
    x2: int
    y2: int
    confidence: float
    class_id: int = 0
    class_name: str = "person"


class FrameResult(BaseModel):
    """Output metrics from processing a single video frame."""
    person_count: int = 0
    density_level: str = "low"  # "low", "medium", "high"
    detections: List[DetectionBox] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    timestamp: float = 0.0


class EventCandidate(BaseModel):
    """
    Candidate event generated by a monitoring plugin.
    Strict Rule: AI detections are NEVER confirmed automatically.
    All events enter the system as 'pending_review'.
    """
    event_type: str
    severity: str = "medium"  # "low", "medium", "high", "critical"
    confidence: float = 0.0
    description: str
    details: Dict[str, Any] = Field(default_factory=dict)
    evidence_path: Optional[str] = None
    timestamp: float = 0.0

    model_config = ConfigDict(arbitrary_types_allowed=True)


class PluginMetadata(BaseModel):
    """Plugin self-describing metadata."""
    name: str
    display_name: str
    version: str = "1.0.0"
    description: str
    domain: str  # "vision", "iot", "multimodal"
    default_config: Dict[str, Any] = Field(default_factory=dict)


class MonitoringPlugin(ABC):
    """
    Standard base class for all OmniSense monitoring plugins.
    Enforces a uniform lifecycle and data processing interface.
    """

    @abstractmethod
    def get_metadata(self) -> PluginMetadata:
        """Returns plugin metadata, description, and default config."""
        pass

    @abstractmethod
    def validate_config(self, config: Dict[str, Any]) -> Dict[str, Any]:
        """Validates and merges user configuration with defaults."""
        pass

    @abstractmethod
    def initialize(self, config: Dict[str, Any]) -> None:
        """Initializes internal plugin state, models, and thresholds."""
        pass

    @abstractmethod
    def process_frame(self, frame: np.ndarray) -> Optional[FrameResult]:
        """Processes an incoming visual frame. Returns FrameResult or None."""
        pass

    @abstractmethod
    def process_sensor_data(self, data: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Processes incoming telemetry metrics. Returns processed metrics or None."""
        pass

    @abstractmethod
    def generate_events(self) -> List[EventCandidate]:
        """
        Evaluates rules, thresholds, and cooldowns.
        Returns newly generated candidate events for database insertion and operator review.
        """
        pass

    @abstractmethod
    def stop(self) -> None:
        """Cleans up resources, background workers, or caches."""
        pass
